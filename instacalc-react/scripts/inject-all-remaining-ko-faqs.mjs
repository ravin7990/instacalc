let updatedCount = 0;

for (const [slug, faqs] of Object.entries(FAQS_BY_SLUG)) {
  const filePath = join(KO_DIR, `${slug}.html`);
  let content = "";
  try {
    content = readFileSync(filePath, "utf-8");
  } catch (e) {
    console.error(`File not found: ${filePath}`);
    continue;
  }

  // Generate FAQ HTML
  const faqHtml = faqs
    .map(
      (f) => `      <details itemscope itemprop="mainEntity" itemtype="https://schema.org/Question">
        <summary itemprop="name">${f.q}</summary>
        <div itemscope itemprop="acceptedAnswer" itemtype="https://schema.org/Answer">
          <p itemprop="text">${f.a}</p>
        </div>
      </details>`
    )
    .join("\n");

  // Check if faq-section exists
  if (content.includes('class="faq-section"')) {
    // Replace content inside section
    content = content.replace(
      /<section class="faq-section"[^>]*>[\s\S]*?<\/section>/,
      `<section class="faq-section" itemscope itemtype="https://schema.org/FAQPage">\n      <h2>자주 묻는 질문 (FAQ)</h2>\n${faqHtml}\n    </section>`
    );
  } else {
    // Insert before </root> or before </div>\n  <script
    const insertionPoint = '</div>\n  <script type="module" src="/src/entry-client.tsx"></script>';
    if (content.includes(insertionPoint)) {
      content = content.replace(
        insertionPoint,
        `  <section class="faq-section" itemscope itemtype="https://schema.org/FAQPage">\n      <h2>자주 묻는 질문 (FAQ)</h2>\n${faqHtml}\n    </section>\n  ` + insertionPoint
      );
    } else {
      // Fallback before </body>
      content = content.replace(
        '</body>',
        `  <section class="faq-section" itemscope itemtype="https://schema.org/FAQPage">\n      <h2>자주 묻는 질문 (FAQ)</h2>\n${faqHtml}\n    </section>\n</body>`
      );
    }
  }

  writeFileSync(filePath, content, "utf-8");
  updatedCount++;
  console.log(`[injected] ${slug}.html with ${faqs.length} FAQs`);
}

console.log(`[done] Injected FAQs into ${updatedCount} Korean HTML files.`);
